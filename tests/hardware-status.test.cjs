const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const vm = require('node:vm')
const {spawnSync} = require('node:child_process')

const base = path.resolve(__dirname, '../plugins/hardware-status')
const model = vm.runInNewContext(fs.readFileSync(path.join(base, 'Model.js'), 'utf8') +
  '\n({parse, primaryTemperature, averageGhz, highestGhz, barText})')

function put(root, name, value) {
  const file = path.join(root, name)
  fs.mkdirSync(path.dirname(file), {recursive: true})
  fs.writeFileSync(file, value)
}

test('samples unprivileged memory, clocks and sensors', t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'hardware-status-'))
  t.after(() => fs.rmSync(root, {recursive: true, force: true}))
  put(root, 'proc/meminfo', 'MemTotal: 4194304 kB\nMemAvailable: 1048576 kB\nSwapTotal: 2097152 kB\nSwapFree: 1572864 kB\n')
  put(root, 'sys/devices/system/cpu/cpu0/cpufreq/scaling_cur_freq', '2400000\n')
  put(root, 'sys/devices/system/cpu/cpu0/cpufreq/cpuinfo_max_freq', '3000000\n')
  put(root, 'sys/devices/system/cpu/cpu0/cpufreq/scaling_max_freq', '2800000\n')
  put(root, 'sys/devices/system/cpu/cpu1/cpufreq/scaling_cur_freq', '1800000\n')
  put(root, 'sys/devices/system/cpu/cpu1/cpufreq/cpuinfo_max_freq', '2600000\n')
  put(root, 'sys/devices/system/cpu/cpu1/cpufreq/scaling_max_freq', '2400000\n')
  put(root, 'sys/class/hwmon/hwmon0/name', 'coretemp\n')
  put(root, 'sys/class/hwmon/hwmon0/temp1_label', 'Package id 0\n')
  put(root, 'sys/class/hwmon/hwmon0/temp1_input', '45500\n')
  put(root, 'sys/class/hwmon/hwmon1/name', 'acpitz\n')
  put(root, 'sys/class/hwmon/hwmon1/temp1_input', '37000\n')
  put(root, 'sys/class/power_supply/BAT0/power_now', '12500000\n')
  put(root, 'sys/class/powercap/intel-rapl/intel-rapl:0/energy_uj', '99999\n')
  const result = spawnSync(path.join(base, 'scripts/sample'), {env: {...process.env, SAMPLE_ROOT: root}, encoding: 'utf8'})
  assert.equal(result.status, 0, result.stderr)
  assert.doesNotMatch(result.stdout, /99999|energy_uj|RAPL|12500000|BAT0/)
  const data = model.parse(result.stdout)
  assert.equal(data.totalKiB, 4194304)
  assert.equal(data.availableKiB, 1048576)
  assert.equal(data.cpus.length, 2)
  assert.equal(model.averageGhz(data.cpus), 2.1)
  assert.equal(model.highestGhz(data.cpus, 'maxGhz'), 3)
  assert.equal(model.highestGhz(data.cpus, 'limitGhz'), 2.8)
  assert.equal(model.primaryTemperature(data.sensors).celsius, 45.5)
  assert.equal(data.swapTotalKiB, 2097152)
  assert.equal(data.swapFreeKiB, 1572864)
  assert.equal(model.barText(data), '3.0G · 2.10GHz · 46°C')
})

test('missing readings remain unavailable and sensor text is bounded', () => {
  const data = model.parse('M\t\t\t\t\nT\tcoretemp\t<img src=x>\t45000\nC\t0\tbad\n')
  assert.equal(data.totalKiB, null)
  assert.equal(data.cpus.length, 0)
  assert.equal(model.highestGhz(data.cpus, 'maxGhz'), null)
  assert.equal(data.sensors[0].label, '<img src=x>')
  assert.equal(model.primaryTemperature(data.sensors).celsius, 45)
})
